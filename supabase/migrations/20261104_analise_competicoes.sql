-- Módulo "Análise de Competições"
-- Correr no Supabase: SQL Editor -> colar este ficheiro -> Run

-- 1. Competições
create table if not exists public.analise_competicoes (
  id bigint generated by default as identity primary key,
  nome text not null,
  data date not null,
  created_at timestamptz not null default now()
);

-- 2. Atletas inscritos numa competição (com género e categoria de peso)
create table if not exists public.analise_atletas (
  id bigint generated by default as identity primary key,
  competicao_id bigint not null references public.analise_competicoes(id) on delete cascade,
  aluno_id bigint references public.alunos(id) on delete set null,
  nome text not null,
  genero text not null check (genero in ('Feminino', 'Masculino')),
  categoria text not null,
  created_at timestamptz not null default now()
);
create index if not exists analise_atletas_competicao_idx on public.analise_atletas(competicao_id);

-- 3. Combates de cada atleta (vídeo guardado no Storage, bucket "combates")
create table if not exists public.analise_combates (
  id bigint generated by default as identity primary key,
  atleta_id bigint not null references public.analise_atletas(id) on delete cascade,
  adversario text,
  ronda text,
  resultado text check (resultado in ('Vitória', 'Derrota')),
  video_path text not null,
  notas text,
  created_at timestamptz not null default now()
);
create index if not exists analise_combates_atleta_idx on public.analise_combates(atleta_id);

-- 4. Segurança: apenas treinadores autenticados
alter table public.analise_competicoes enable row level security;
alter table public.analise_atletas enable row level security;
alter table public.analise_combates enable row level security;

drop policy if exists "treinadores_all" on public.analise_competicoes;
create policy "treinadores_all" on public.analise_competicoes
  for all to authenticated using (true) with check (true);

drop policy if exists "treinadores_all" on public.analise_atletas;
create policy "treinadores_all" on public.analise_atletas
  for all to authenticated using (true) with check (true);

drop policy if exists "treinadores_all" on public.analise_combates;
create policy "treinadores_all" on public.analise_combates
  for all to authenticated using (true) with check (true);

-- 5. Bucket privado para os vídeos dos combates
insert into storage.buckets (id, name, public)
values ('combates', 'combates', false)
on conflict (id) do nothing;

drop policy if exists "combates_treinadores_select" on storage.objects;
create policy "combates_treinadores_select" on storage.objects
  for select to authenticated using (bucket_id = 'combates');

drop policy if exists "combates_treinadores_insert" on storage.objects;
create policy "combates_treinadores_insert" on storage.objects
  for insert to authenticated with check (bucket_id = 'combates');

drop policy if exists "combates_treinadores_update" on storage.objects;
create policy "combates_treinadores_update" on storage.objects
  for update to authenticated using (bucket_id = 'combates');

drop policy if exists "combates_treinadores_delete" on storage.objects;
create policy "combates_treinadores_delete" on storage.objects
  for delete to authenticated using (bucket_id = 'combates');
