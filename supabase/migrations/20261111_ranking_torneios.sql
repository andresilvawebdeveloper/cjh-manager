-- RANKING DE TORNEIOS (por ano de nascimento + competição entre centros)
-- Correr no Supabase: SQL Editor -> colar este ficheiro -> Run
-- Pontos: 1.º lugar = 5, 2.º lugar = 3, 3.º lugar = 1, sem pódio = 0
-- =====================================================================

-- Épocas: cada época define os anos de nascimento que entram no ranking
create table if not exists public.ranking_epocas (
  id bigint generated by default as identity primary key,
  nome text not null unique,                 -- ex: "2026/2027"
  anos jsonb not null,                       -- ex: [{"ano":2017,"escalao":"Benjamins"}, ...]
  created_at timestamptz not null default now()
);

-- Centros/polos (do clube e de fora, ex: Pião Mágico)
create table if not exists public.ranking_centros (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  created_at timestamptz not null default now()
);

-- Provas (torneios) de uma época
create table if not exists public.ranking_provas (
  id bigint generated by default as identity primary key,
  epoca_id bigint not null references public.ranking_epocas(id) on delete cascade,
  nome text not null,
  data date not null,
  created_at timestamptz not null default now()
);
create index if not exists ranking_provas_epoca_idx on public.ranking_provas(epoca_id);

-- Atletas do ranking (uma vez por época; reaproveitados entre provas)
create table if not exists public.ranking_atletas (
  id bigint generated by default as identity primary key,
  epoca_id bigint not null references public.ranking_epocas(id) on delete cascade,
  nome text not null,
  ano integer not null,
  centro_id bigint references public.ranking_centros(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (epoca_id, nome, ano)
);

-- Resultados: um atleta numa prova
create table if not exists public.ranking_resultados (
  id bigint generated by default as identity primary key,
  prova_id bigint not null references public.ranking_provas(id) on delete cascade,
  atleta_id bigint not null references public.ranking_atletas(id) on delete cascade,
  centro_id bigint references public.ranking_centros(id) on delete set null, -- centro por que competiu nesta prova
  peso text,
  classificacao text not null check (classificacao in ('1º', '2º', '3º', 'Sem pódio')),
  created_at timestamptz not null default now(),
  unique (prova_id, atleta_id)
);
create index if not exists ranking_resultados_prova_idx on public.ranking_resultados(prova_id);

